# Math Operations
print(3 + 4)   # addition(+)
print(3 - 4)   # subtraction(-)
print(3 * 4)   # multiplication(*)
print(3 % 4)   # modulus(%)
print(3 / 4)   # division(/)
print(3 ** 4)  # exponential(**)
print(3 // 4)  # Floor division operator(//)

# Strings
print('Ricky')      # My name
print("Gonzalez")   # My family name
print('Mexico')     # My country
print('''I am enjoying 30 days of python''')

# Checking data types
print(type(10))
print(type(9.8))
print(type(3.14))
print(type(4 - 4j))
print(type(['Azabaneh', 'Python', 'Finland']))
print(type('Ricky'))
print(type("Gonzalez"))
